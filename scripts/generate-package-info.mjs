import { readFile, writeFile } from "node:fs/promises";

const packageJsonUrl = new URL("../package.json", import.meta.url);
const outputUrl = new URL("../src/debug/package-info.ts", import.meta.url);
const packageJson = JSON.parse(await readFile(packageJsonUrl, "utf8"));

await writeFile(
  outputUrl,
  `// Generated by scripts/generate-package-info.mjs. Do not edit manually.\nexport const OMINITY_NEXT_PACKAGE_VERSION = ${JSON.stringify(packageJson.version)};\n`,
);
